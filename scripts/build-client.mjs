import fs from 'node:fs';
import path from 'node:path';
import vm from 'node:vm';
import { fileURLToPath } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const srcDir = path.join(root, 'src');
const outfile = path.join(root, 'client.js');

/* The browser half is shipped as one file, so the source stays split for
   maintenance and this script assembles the factory body in order. */
const files = [
  'constants.js',
  'dictionaries.js',
  'dates.js',
  'store-seed.js',
  'store-sanitize.js',
  'store-appearance.js',
  'store-create.js',
  'helpers.js',
  'icons.js',
  'todos.js',
  'month-grid.js',
  'mini-month.js',
  'heatmap.js',
  'notes.js',
  'settings.js',
  'panel.js',
  'styles.js',
  'plugin.js',
];

const header = `// Generated by scripts/build-client.mjs from src/. Do not edit this file directly.

/**
 * Browser half of the Keep-style notes & todos bundle.
 *
 * Renders one root-scoped main panel (key \`keep-notes\`) and its sidebar entry in
 * \`sidebar.panellist\`. The panel keeps its own board in browser storage, so the
 * Host contributes nothing but the Loader row.
 */
window.__ModuleLoader__.load({
  id: 'dsh-keep-notes',
  factory(require) {
    const React = require('react');
    const h = React.createElement;

`;

const footer = `    return { inject: inject, apply: apply };
  },
});
`;

const body = files
  .map((file) => {
    const source = fs
      .readFileSync(path.join(srcDir, file), 'utf8')
      .replace(/\r\n/g, '\n')
      .replace(/\s+$/, '');
    if (!source.trim()) throw new Error('empty source file: ' + file);
    /* Each fragment is a factory-scope slice, so parse it on its own first. */
    new vm.Script(source, { filename: 'src/' + file });
    const banner = `    /* --------------------------------------------------------------------- */\n    /* src/${file}${' '.repeat(Math.max(1, 67 - file.length))}*/\n    /* --------------------------------------------------------------------- */\n\n`;
    return banner + source;
  })
  .join('\n\n');

const output = header + body + '\n\n' + footer;
const check = process.argv.includes('--check');

if (check) {
  const current = fs.readFileSync(outfile, 'utf8').replace(/\r\n/g, '\n');
  if (current !== output) {
    console.error('client.js is stale; run npm run build:client and commit the result.');
    process.exitCode = 1;
  } else {
    console.log('client.js is up to date (' + files.length + ' source files).');
  }
} else {
  fs.writeFileSync(outfile, output);
  console.log('built client.js from ' + files.length + ' source files (' + output.length + ' bytes).');
}
